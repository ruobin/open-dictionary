/**
 * HTTP response shape. Mirrors the frontend `DictionaryEntry`
 * (src/api/dictionary.ts) so the existing UI renders both tiers unchanged —
 * the client already casts the JSON to `DictionaryEntry[]`. The Mongo cache
 * stores this same shape under `entries`.
 */
interface Phonetic {
  text?: string
  audio?: string
}
export interface GradedExample {
  text: string
  cefr?: CefrLevel
}
interface Definition {
  definition: string
  cefr?: CefrLevel
  grammar?: string
  register?: string
  /** 1-3 example sentences at different CEFR levels — the core learner pitch (to-do §3). */
  examples?: GradedExample[]
}
interface Meaning {
  partOfSpeech: string
  definitions: Definition[]
}
export interface CommonMistake {
  wrong: string
  right: string
  note?: string
}
export interface TypoSuggestion {
  /** The likely intended word. */
  suggestion: string
  /** Short human-readable note for the user. */
  explanation?: string
}
export interface DictionaryEntry {
  word: string
  phonetic?: string
  phonetics: Phonetic[]
  /** Grouped by part of speech — "run" (verb) and "run" (noun) are separate entries. */
  meanings: Meaning[]
  sourceUrls?: string[]
  /** Best short translation into targetLang; only present when sourceLang !== targetLang. */
  translation?: string
  /** Learner-corpus-style corrections, e.g. "make a photo" → "take a photo". */
  commonMistakes?: CommonMistake[]
  /** Fixed expressions this word commonly appears in, e.g. "heavy rain". */
  collocations?: string[]
  /** Related words, e.g. run → runner, running, rerun. */
  wordFamily?: string[]
  /** Present only when the LLM judged the input to be an obvious typo. */
  typo?: TypoSuggestion
  /** Which LLM model(s) wrote this entry (word page "Generated by" footnote).
   *  Absent on dictionary-tier entries and on cache entries created before
   *  2026-10-30. */
  generatedBy?: GeneratedBy
}

export interface GeneratedBy {
  /** Model names, e.g. `openai/gpt-6-luna`, `deepseek-v4-flash`. */
  models: string[]
  /** True when the entry is a fusion merge of several models' answers. */
  merged?: boolean
}

/** `llm:<vendor>:<model>` → `<model>` (model ids may themselves contain ':'). */
export function modelNameFromProviderId(id: string): string {
  const m = /^llm:[^:]+:(.+)$/.exec(id)
  return m ? m[1] : id
}

function withGeneratedBy(entries: DictionaryEntry[], providerIds: string[], merged = false): DictionaryEntry[] {
  const models = [...new Set(providerIds.map(modelNameFromProviderId).filter(Boolean))]
  if (models.length === 0) return entries
  const generatedBy: GeneratedBy = merged && models.length > 1 ? { models, merged: true } : { models }
  return entries.map((e) => ({ ...e, generatedBy }))
}

interface TranslateRequest {
  text: string
  sourceLang: string
  targetLang: string
}

export interface TranslateOutcome {
  entries: DictionaryEntry[]
  tier: 'cache' | 'llm' | 'dictionary'
}

const MAX_TEXT_LENGTH = MAX_LOOKUP_TEXT_LENGTH

// Whitelist of accepted language codes. Rejecting unknown `from`/`to` values
// bounds the cache cardinality and prevents LLM-cost abuse (every distinct
// (word, sourceLang, targetLang) tuple would otherwise create a cache doc +
// trigger a paid LLM call).
const LANGUAGE_CODES = new Set(LANGUAGES.map((l) => l.code))

const LLM_DEBUG = /^(1|true|yes|on)$/i.test(process.env.LLM_DEBUG ?? '')

/**
 * Cache-key version component (to-do §2). Bump whenever `adaptLlm()`'s output
 * shape changes, or the LLM prompt/schema in
 * `server/providers/llm/openaiCompat.ts` (`buildMessages`/`parseContent`)
 * changes in a way that would produce a different cached result for the same
 * input — otherwise the change is invisible for up to the 1-year cache TTL.
 * Old-version cache docs are left to TTL-expire rather than eagerly purged
 * (see docs/design-translation-cache.md §2).
 */
export const CACHE_VERSION = 'v3'

export const translateLimiter = rateLimit({
  windowMs: 60 * 1000,
  max: TRANSLATE_RATE_LIMIT_RPM,
  standardHeaders: true,
  legacyHeaders: false,
  message: { error: 'rate_limited' },
})

export function normalizeText(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .normalize('NFC')
    .replace(/\s+/g, ' ')
    .replace(/[\u0000-\u001f\u007f]/g, '') // strip non-whitespace control chars (log/cache integrity)
    .slice(0, MAX_TEXT_LENGTH)
}

/** Returns the validated lowercase language code, or `null` if not in the
 *  supported set. An undefined value resolves to `fallback` (a known code). */
function normalizeLang(value: string | undefined, fallback: string): string | null {
  if (value === undefined || value.trim() === '') return fallback
  const code = value.trim().toLowerCase()
  return LANGUAGE_CODES.has(code) ? code : null
}

function adaptGradedExample(e: LlmGradedExample): GradedExample {
  return e.cefr ? { text: e.text, cefr: e.cefr } : { text: e.text }
}

function adaptSense(s: LlmSense): Definition {
  const def: Definition = { definition: s.definition }
  if (s.cefr) def.cefr = s.cefr
  if (s.grammar) def.grammar = s.grammar
  if (s.register) def.register = s.register
  if (s.examples && s.examples.length > 0) def.examples = s.examples.map(adaptGradedExample)
  return def
}

/** Maps the LLM's structured content into the dictionary-entry render shape. */
export function adaptLlm(content: LlmTranslationContent): DictionaryEntry[] {
  const meanings: Meaning[] = Array.isArray(content.meaningGroups)
    ? content.meaningGroups.map((g) => ({
        partOfSpeech: g.partOfSpeech,
        definitions: g.senses.map(adaptSense),
      }))
    : []

  const phonetics: Phonetic[] = content.phonetic ? [{ text: content.phonetic }] : []

  const entry: DictionaryEntry = {
    word: content.headword || '',
    phonetics,
    meanings,
  }
  if (content.phonetic) entry.phonetic = content.phonetic
  if (content.translation) entry.translation = content.translation
  if (content.commonMistakes && content.commonMistakes.length > 0) {
    entry.commonMistakes = content.commonMistakes
  }
  if (content.collocations && content.collocations.length > 0) entry.collocations = content.collocations
  if (content.wordFamily && content.wordFamily.length > 0) entry.wordFamily = content.wordFamily
  if (content.typo) {
    entry.typo = content.typo.explanation
      ? { suggestion: content.typo.suggestion, explanation: content.typo.explanation }
      : { suggestion: content.typo.suggestion }
  }

  return [entry]
}

async function cacheSetSafe(
  cache: TranslationCache | null | undefined,
  req: TranslateRequest,
  entries: DictionaryEntry[],
  source: string,
  createdBy?: EntryCreator
): Promise<void> {
  if (!cache) return
  try {
    if (createdBy) await cache.set(req.text, req.sourceLang, req.targetLang, entries, source, CACHE_VERSION, createdBy)
    else await cache.set(req.text, req.sourceLang, req.targetLang, entries, source, CACHE_VERSION)
  } catch (err) {
    console.warn('[cache] write failed (non-fatal):', err)
  }
}

/** How long, after the LLM answer is ready, to keep waiting for the (parallel)
 *  pronunciation-audio lookup before answering without it. */
const AUDIO_GRACE_MS = 1_500

/** Best-effort: fetch audio URLs from the Free Dictionary API. Only attempts for
 *  English source words (the dict API is English-only). NEVER rejects — a
 *  failure just means the entry has no audio. Started in parallel with the LLM
 *  call so it adds no latency in the common case. */
async function fetchAudioPhonetics(req: TranslateRequest, dictionary: DictionaryProvider): Promise<Phonetic[]> {
  if (req.sourceLang.toLowerCase() !== 'en') return []
  try {
    const raw = await dictionary.define({ text: req.text, sourceLang: req.sourceLang })
    if (!Array.isArray(raw) || raw.length === 0) {
      if (LLM_DEBUG) {
        console.log(`[dict-audio] no entries from dictionary for "${req.text}" (sourceLang=${req.sourceLang})`)
      }
      return []
    }
    const dictPhonetics = (raw[0] as DictionaryEntry)?.phonetics ?? []
    const audioPhonetics = dictPhonetics.filter((p) => Boolean(p.audio))
    if (LLM_DEBUG) {
      console.log(`[dict-audio] "${req.text}": ${dictPhonetics.length} phonetics, ${audioPhonetics.length} with audio`)
    }
    return audioPhonetics
  } catch (err) {
    if (LLM_DEBUG) {
      const message = err instanceof Error ? err.message : String(err)
      console.log(`[dict-audio] dictionary call failed for "${req.text}": ${message}`)
    }
    return []
  }
}

function withAudio(entries: DictionaryEntry[], audio: Phonetic[]): DictionaryEntry[] {
  if (audio.length === 0) return entries
  return entries.map((entry, i) =>
    i === 0 ? { ...entry, phonetics: [...(entry.phonetics ?? []), ...audio] } : entry
  )
}

/** Resolves with the promise's value, or `null` if it is not ready within `ms`. */
function withinGrace<T>(promise: Promise<T>, ms: number): Promise<T | null> {
  return new Promise<T | null>((resolve) => {
    const timer = setTimeout(() => resolve(null), ms)
    promise.then(
      (value) => {
        clearTimeout(timer)
        resolve(value)
      },
      () => {
        clearTimeout(timer)
        resolve(null)
      }
    )
  })
}

type PartialListener = (entries: DictionaryEntry[]) => void

/**
 * In-flight request dedup (to-do §9): concurrent lookups for the same
 * (text, sourceLang, targetLang) share one underlying `doTranslate()` call
 * instead of each fanning out to the cache/LLM/dictionary — protects a
 * popular uncached word from a stampede of simultaneous LLM calls. Joiners also
 * receive the streamed partial answers (the latest one immediately on join).
 * An entry stays registered until its background work (cache writes, fusion
 * upgrade) has settled, so a request arriving between "response sent" and
 * "cache written" joins instead of launching a duplicate paid LLM call.
 */
interface InFlight {
  promise: Promise<TranslateOutcome>
  listeners: Set<PartialListener>
  last?: DictionaryEntry[]
  /** The outcome is known (only background cache writes remain): joiners get no
   *  stale partial replayed, just the final result. */
  settled?: boolean
}
const inFlight = new Map<string, InFlight>()

function inFlightKey(req: TranslateRequest): string {
  return `${req.sourceLang}|${req.targetLang}|${req.text}`
}

/** True when this lookup can be answered without a new paid LLM call: it is
 *  already in flight (a joiner pays nothing), or it is in the cache. Used only
 *  for clients over their daily LLM budget, so the extra cache read is not on
 *  the normal path. */
export async function canServeWithoutLlm(
  req: TranslateRequest,
  cache: TranslationCache | null | undefined
): Promise<boolean> {
  if (inFlight.has(inFlightKey(req))) return true
  if (!cache) return false
  try {
    return Boolean(await cache.get(req.text, req.sourceLang, req.targetLang, CACHE_VERSION))
  } catch {
    return false
  }
}

function subscribe(state: InFlight, listener: PartialListener | undefined): void {
  if (!listener) return
  state.listeners.add(listener)
  if (state.last && !state.settled) {
    try {
      listener(state.last)
    } catch {
      // a broken listener (e.g. a closed socket) must never affect the lookup
    }
  }
}

export interface TranslateHooks {
  /** Called with progressively more complete entries while the LLM is still writing. */
  onPartial?: PartialListener
  /** The client starting this lookup; stored as the cache doc's `createdBy`
   *  if the lookup creates one. In-flight joiners don't overwrite it. */
  client?: EntryCreator
}

/**
 * Read-through, tiered lookup: Mongo cache → LLM (primary) → dictionary
 * (fallback only on LLM failure/absence). Results are cached keyed by
 * (word, sourceLang, targetLang, version) (design doc §5, §6; to-do §2).
 */
export function translate(
  req: TranslateRequest,
  llm: LlmProvider | null,
  dictionary: DictionaryProvider,
  cache?: TranslationCache | null,
  hooks: TranslateHooks = {}
): Promise<TranslateOutcome> {
  const key = inFlightKey(req)
  const existing = inFlight.get(key)
  if (existing) {
    subscribe(existing, hooks.onPartial)
    return existing.promise
  }

  const state: InFlight = { promise: undefined as unknown as Promise<TranslateOutcome>, listeners: new Set() }
  subscribe(state, hooks.onPartial)
  const background: Array<Promise<unknown>> = []
  const emit: PartialListener = (entries) => {
    // A model that is still writing after the answer was chosen (fusion's
    // slower provider) must not push stale snapshots after the result.
    if (state.settled) return
    state.last = entries
    for (const listener of state.listeners) {
      try {
        listener(entries)
      } catch {
        // see subscribe()
      }
    }
  }

  state.promise = doTranslate(req, llm, dictionary, cache, emit, background, hooks.client).then((outcome) => {
    state.settled = true
    recordOutcome(outcome.tier)
    return outcome
  })
  inFlight.set(key, state)

  const release = (): void => {
    if (background.length === 0) inFlight.delete(key)
    else void Promise.allSettled(background).then(() => inFlight.delete(key))
  }
  state.promise.then(release, release)
  return state.promise
}

async function doTranslate(
  req: TranslateRequest,
  llm: LlmProvider | null,
  dictionary: DictionaryProvider,
  cache: TranslationCache | null | undefined,
  emit: PartialListener,
  background: Array<Promise<unknown>>,
  client?: EntryCreator
): Promise<TranslateOutcome> {
  // Cache writes for one lookup are serialised so a late audio/fusion
  // write can never be overtaken by (and lost to) the first write.
  let writeChain: Promise<void> = Promise.resolve()
  const enqueueWrite = (fn: () => Promise<void>): void => {
    if (!cache) return
    writeChain = writeChain.then(fn)
    background.push(writeChain)
  }

  // Tier 0 — cache
  if (cache) {
    try {
      const hit = await cache.get(req.text, req.sourceLang, req.targetLang, CACHE_VERSION)
      if (hit) return { entries: hit.entries, tier: 'cache' }
    } catch (err) {
      console.warn('[cache] read failed (continuing to providers):', err)
    }
  }

  // Tier 1 — LLM (primary)
  if (llm) {
    const started = Date.now()
    // Pronunciation audio is independent of the LLM answer — fetch it concurrently.
    const audioPromise = fetchAudioPhonetics(req, dictionary)
    try {
      const result = await llm.translate(req, {
        onPartial: (partial) => {
          const preview = adaptLlm(partial)
          if (preview.some((e) => e.word || e.meanings.length > 0)) emit(preview)
        },
      })
      recordLlmLatency(llm.id, Date.now() - started)
      const content = result.content as LlmTranslationContent
      let entries = withGeneratedBy(adaptLlm(content), result.generatedBy ?? [llm.id])
      const isTypoResponse = entries.some((e) => Boolean(e.typo?.suggestion))
      if (entries.some((e) => e.word || e.meanings.length > 0)) {
        let lateAudio: Promise<Phonetic[]> | null = null
        if (!isTypoResponse) {
          const audio = await withinGrace(audioPromise, AUDIO_GRACE_MS)
          if (audio) entries = withAudio(entries, audio)
          else lateAudio = audioPromise
        }

        // Partial answers (extras call failed) are served but never cached —
        // caching would freeze the missing sections in for the cache TTL.
        if (!result.incomplete) {
          const firstEntries = entries
          enqueueWrite(() => cacheSetSafe(cache, req, firstEntries, 'llm', client))
          if (lateAudio) {
            const pending = lateAudio
            enqueueWrite(async () => {
              const audio = await pending
              if (audio.length > 0) await cacheSetSafe(cache, req, withAudio(firstEntries, audio), 'llm', client)
            })
          }
        }

        // Fusion: a fast first answer was returned; the merged entry arrives
        // later and replaces the cached one for every subsequent lookup.
        if (result.upgrade) {
          const upgrade = result.upgrade
          background.push(
            upgrade
              .then(async (merged) => {
                if (!merged) return
                let upgraded = withGeneratedBy(adaptLlm(merged), result.upgradeGeneratedBy ?? [llm.id], true)
                if (!upgraded.some((e) => e.word || e.meanings.length > 0)) return
                if (!upgraded.some((e) => Boolean(e.typo?.suggestion))) {
                  upgraded = withAudio(upgraded, await audioPromise)
                }
                enqueueWrite(() => cacheSetSafe(cache, req, upgraded, 'llm', client))
                await writeChain
              })
              .catch((err: unknown) => console.warn('[translate] fusion upgrade failed (non-fatal):', err))
          )
        }
        return { entries, tier: 'llm' }
      }
    } catch (err) {
      const e = err as Error & { code?: string; status?: number }
      recordLlmError(llm.id, e?.code ?? e?.name ?? 'unknown')
      recordDictFallbackUsed()
      console.warn(
        `[translate] LLM tier failed (${e?.name || 'Error'}${e?.code ? `/${e.code}` : ''}${
          e?.status ? ` ${e.status}` : ''
        }): ${e?.message || e}. Falling back to dictionary.`
      )
      if (LLM_DEBUG) console.warn('[translate] full error:', err)
    }
  }

  // Tier 2 — dictionary (fallback)
  let raw: unknown
  try {
    raw = await dictionary.define({ text: req.text, sourceLang: req.sourceLang })
  } catch (err) {
    recordDictError()
    throw err
  }
  const entries = raw as DictionaryEntry[]
  enqueueWrite(() => cacheSetSafe(cache, req, entries, 'dict', client))
  return { entries, tier: 'dictionary' }
}

interface ParsedLookup {
  text: string
  sourceLang: string
  targetLang: string
}

/** Validates `:text` + `from`/`to`. Sends the error response itself and
 *  returns null when the request is invalid. */
function parseLookup(req: Request, res: Response): ParsedLookup | null {
  const text = normalizeText(req.params.text)
  if (!text) {
    res.status(404).json({ error: 'not_found' })
    return null
  }
  const sourceLang = normalizeLang(typeof req.query.from === 'string' ? req.query.from : undefined, 'en')
  const targetLang = normalizeLang(typeof req.query.to === 'string' ? req.query.to : undefined, 'en')
  if (sourceLang === null || targetLang === null) {
    res.status(400).json({ error: 'invalid_language' })
    return null
  }
  return { text, sourceLang, targetLang }
}

function logAndRecord(
  req: Request,
  lookup: ParsedLookup,
  outcome: TranslateOutcome,
  latencyMs: number,
  extra: Record<string, unknown> = {}
): void {
  // Structured per-request log (design doc §12) — textLength, never text.
  console.log(
    '[translate]',
    JSON.stringify({
      tier: outcome.tier,
      sourceLang: lookup.sourceLang,
      targetLang: lookup.targetLang,
      textLength: lookup.text.length,
      latencyMs,
      ...extra,
    })
  )

  // User activity log (docs/design-user-activity-log.md) — fire-and-forget,
  // never awaited, never allowed to affect this response.
  recordActivity({
    word: lookup.text,
    sourceLang: lookup.sourceLang,
    targetLang: lookup.targetLang,
    tier: outcome.tier,
    latencyMs,
    ip: req.ip ?? 'unknown',
    userAgent: req.get('user-agent'),
    origin: req.get('origin'),
  })
  if (outcome.tier === 'llm') recordLlmSpend(req)
}

function entryCreatorFromReq(req: Request): EntryCreator {
  return buildEntryCreator({ ip: clientIp(req), userAgent: req.get('user-agent'), origin: req.get('origin') })
}

function writeSse(res: Response, event: string, data: unknown): void {
  res.write(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`)
}

/** Builds the /api router with GET /translate/:text and GET /translate-stream/:text mounted under /api. */
export function createTranslateRouter(
  dictionary: DictionaryProvider,
  cache?: TranslationCache | null
): Router {
  const router = Router()

  router.get(
    '/translate/:text',
    translateLimiter,
    llmGuard,
    async (req: Request, res: Response, next: NextFunction) => {
      try {
        const lookup = parseLookup(req, res)
        if (!lookup) return
        if (res.locals.llmBudgetExceeded && refuseOverBudget(res, !(await canServeWithoutLlm(lookup, cache)))) return

        const llm = (req.app.locals.llmService as LlmService).current()
        const started = Date.now()
        const outcome = await translate(lookup, llm, dictionary, cache, { client: entryCreatorFromReq(req) })
        const latencyMs = Date.now() - started

        if (outcome.entries.length === 0) {
          res.status(404).json({ error: 'not_found' })
          return
        }

        logAndRecord(req, lookup, outcome, latencyMs)
        res.json(outcome.entries)
      } catch (err) {
        if ((err as { code?: string })?.code === 'not_found') {
          res.status(404).json({ error: 'not_found' })
          return
        }
        next(err)
      }
    }
  )

  /**
   * Same lookup as /translate/:text, delivered as Server-Sent Events so the
   * page can paint the headword/translation/first senses while the LLM is
   * still writing the rest:
   *
   *   event: partial  data: DictionaryEntry[]   (0..n, each more complete than the last)
   *   event: done     data: DictionaryEntry[]   (final; identical to the /translate body)
   *   event: error    data: { error: "not_found" | "internal" }
   *
   * Cache hits send just `done`. Validation errors are ordinary JSON responses
   * with a 4xx status, before any stream starts. Shares translateLimiter and
   * the in-flight dedup with /translate.
   */
  router.get('/translate-stream/:text', translateLimiter, llmGuard, async (req: Request, res: Response) => {
    const lookup = parseLookup(req, res)
    if (!lookup) return
    if (res.locals.llmBudgetExceeded && refuseOverBudget(res, !(await canServeWithoutLlm(lookup, cache)))) return

    res.status(200)
    res.setHeader('Content-Type', 'text/event-stream; charset=utf-8')
    res.setHeader('Cache-Control', 'no-cache, no-transform')
    res.setHeader('Connection', 'keep-alive')
    res.setHeader('X-Accel-Buffering', 'no') // tell nginx not to buffer this response
    res.flushHeaders()

    let closed = false
    res.on('close', () => {
      closed = true
    })
    const send = (event: string, data: unknown): void => {
      if (!closed) writeSse(res, event, data)
    }

    const started = Date.now()
    let firstPartialMs: number | undefined
    try {
      const llm = (req.app.locals.llmService as LlmService).current()
      const outcome = await translate(lookup, llm, dictionary, cache, {
        client: entryCreatorFromReq(req),
        onPartial: (entries) => {
          firstPartialMs ??= Date.now() - started
          send('partial', entries)
        },
      })
      const latencyMs = Date.now() - started

      if (outcome.entries.length === 0) {
        send('error', { error: 'not_found' })
      } else {
        logAndRecord(req, lookup, outcome, latencyMs, { stream: true, ...(firstPartialMs !== undefined ? { firstPartialMs } : {}) })
        send('done', outcome.entries)
      }
    } catch (err) {
      if ((err as { code?: string })?.code === 'not_found') {
        send('error', { error: 'not_found' })
      } else {
        console.error('[api] GET /translate-stream ->', err)
        send('error', { error: 'internal' })
      }
    } finally {
      // Mark closed first so a straggling partial can never write after end().
      const alreadyClosed = closed
      closed = true
      if (!alreadyClosed) res.end()
    }
  })

  return router
}
